export function drawMutIcon(ctx: CanvasRenderingContext2D, id: string, color: string, s: number, ox = 0, oy = 0) {
  const icon = ICONS[id];
  if (!icon) {
    ctx.fillStyle = color;
    const m = 8 * s;
    ctx.fillRect(ox + m - s, oy + 2 * s, 2 * s, 12 * s);
    ctx.fillRect(ox + 2 * s, oy + m - s, 12 * s, 2 * s);
    return;
  }
  for (let y = 0; y < icon.p.length; y++) {
    const row = icon.p[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      ctx.fillStyle = icon.c[ch] ?? color;
      ctx.fillRect(ox + x * s, oy + y * s, s, s);
    }
  }
}

export function MutIcon({ id, color }: { id: string; color: string }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const c = ref.current;
    if (!c) return;
    const ctx = c.getContext('2d');
    if (!ctx) return;
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, 80, 80);
    drawMutIcon(ctx, id, color, 5);
  }, [id, color]);
  return (
    <canvas
      ref={ref}
      width={80}
      height={80}
      className="w-[5.5em] h-[5.5em]"
      style={{ imageRendering: 'pixelated', display: 'block' }}
    />
  );
}

export function MutIconSm({ id, color }: { id: string; color: string }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const c = ref.current;
    if (!c) return;
    const ctx = c.getContext('2d');
    if (!ctx) return;
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, 32, 32);
    drawMutIcon(ctx, id, color, 2);
  }, [id, color]);
  return <canvas ref={ref} width={32} height={32} className="w-[2em] h-[2em]" style={{ imageRendering: 'pixelated' }} />;
}
