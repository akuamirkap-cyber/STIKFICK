// Foot Mode V2: putaran badan. [mulai, selesai, jumlah putaran] dalam waktu pose.
// Sumbu X tiap sendi dikali cos(sudut) terhadap pinggul, sehingga badan tampak menyempit,
// membelakangi lawan, lalu kembali menghadap tepat sebelum tumit menghantam.
const spins: Partial<Record<Pose, readonly [number, number, number]>> = {
  foot_v2_backlash_l: [.07, .33, 1],
  foot_v2_backlash_r: [.06, .32, 1],
  foot_v2_540: [.15, .455, 2],
  foot_v2_senpu: [.20, .56, 2],
  foot_v2_daisenpu: [.18, .52, 2],
  foot_windmill: [.22, .58, 2],
};

export function isFootPose(pose: string) { return pose.startsWith('foot_'); }

export function solveFootPose(o: StickOpts, tall = false): Skeleton {
  const f = o.facing < 0 ? -1 : 1;
  const s = (o.limbScale ?? 1) * o.scale;
  const aim = o.sideView ? 0 : Math.sin(o.aim);
  const frames = poses[o.pose];
  const t = clamp(o.t, 0, 1);
  const sway = Math.sin(o.time * 4.6);
  const side = Math.cos(o.time * 4.6);
  let step = 0;
  if (frames) while (step < frames.length - 2 && t > frames[step + 1][0]) step++;
  const [a, first] = frames?.[step] ?? [0, ready];
  const [b, last] = frames?.[step + 1] ?? [1, ready];
  const u = clamp((t - a) / (b - a), 0, 1);
  const smooth = u * u * (3 - 2 * u), ahead = frames?.[step + 2], behind = frames?.[step - 1];
  // Carry momentum through adjacent frames without overshooting a planted foot.
  const interpolate = (i: number) => {
    const v0 = first[i], v1 = last[i], d = v1 - v0;
    if (Math.abs(d) < .001 || !frames) return lerp(v0, v1, smooth);
    const safeSlope = (slope: number) => Math.sign(slope) === Math.sign(d) ? Math.sign(d) * Math.min(Math.abs(slope), 1.6 * Math.abs(d)) : 0;
    const m0 = behind ? safeSlope((v1 - behind[1][i]) * (b - a) / (b - behind[0])) : 0;
    const m1 = ahead ? safeSlope((ahead[1][i] - v0) * (b - a) / (ahead[0] - a)) : 0;
    return lerp(v0, v1, smooth) + u * (1 - u) * ((1 - u) * m0 - u * m1);
  };
  // POSTUR: badan tidak lagi rebah jauh ke belakang saat menendang. Bahu & kepala ditarik kembali
  // ke atas pinggul (tetap sedikit condong), kecuali saat akrobat terbalik / bertumpu tangan.
  const hipX = interpolate(0), upright = clamp((interpolate(1) - interpolate(3) - 1.4) / 1.8, 0, 1);
  const fixNeck = -Math.min(0, interpolate(2) - hipX + .45) * .7 * upright;
  const fixHead = -Math.min(0, interpolate(4) - hipX + .3) * .7 * upright;
  const spin = spins[o.pose];
  const turn = spin && t > spin[0] && t < spin[1] ? Math.cos((t - spin[0]) / (spin[1] - spin[0]) * Math.PI * 2 * spin[2]) : 1;
  // Aturan terpenting: dagu ditempelkan ke dada saat berputar sejajar lantai, sehingga yang menghadap
  // lantai adalah punggung atas — belakang kepala tidak pernah membentur lantai.
  const tucking = o.pose === 'foot_rdk' && t > .60 && t < .84;
  const pivot = turn !== 1 ? interpolate(0) : 0;
  const joint = (index: number): Vec => {
    let x = interpolate(index), y = interpolate(index + 1);
    if (index === 2) { x += fixNeck; y -= fixNeck * .22; }
    else if (index === 4) { x += fixHead; y -= fixHead * .26; }
    else if (index >= 10) x += fixNeck * .8;
    if (turn !== 1 && index !== 0) x = pivot + (x - pivot) * turn;
    if (!frames || o.pose === 'foot_flamingo') {
      if (index <= 4) { x += sway * 0.41; y += side * 0.33; }
      if (index === 6 || index === 8) y -= Math.max(0, (index === 6 ? sway : -sway)) * 0.63;
      if (index >= 10) { x += sway * -0.48; y += side * 0.48; }
    }
    if (o.pose === 'foot_v2_guard') {
      // Pantulan khas Taekwondo: badan memantul, kedua kaki bergantian berjingkat.
      const wave = Math.sin(o.time * 7.4), hop = Math.abs(wave);
      if (index <= 4) { y -= hop * .62; x += wave * .16; }
      if (index === 6) { y -= Math.max(0, wave) * .95; x += Math.max(0, wave) * .35; }
      if (index === 8) { y -= Math.max(0, -wave) * .7; }
      if (index >= 10) { y += hop * .42 - .3; x += wave * (index === 10 ? .3 : -.3); }
    }
    const squash = 1 + ((o.squash ?? 1) - 1) * .48;
    return { x: x * s * f * (tall ? 1.07 : 1) * (1 + (1 - squash) * .32), y: (y + x * aim * 0.25) * s * (tall ? 1.27 : 1) * squash };
  };
  let hip = joint(0), neck = joint(2), head = joint(4), ffoot = joint(6), bfoot = joint(8), fhand = joint(10), bhand = joint(12);
  if (tucking) {
    // Barrel roll sejajar lantai: tubuh tetap mendatar, anggota badan berputar mengelilingi sumbu badan,
    // dagu menempel ke dada supaya punggung atas yang menghadap lantai.
    const roll = Math.cos((t - .60) / (.84 - .60) * Math.PI * 2);
    const axisY = (hip.y + neck.y) / 2;
    const r = (v: Vec): Vec => ({ x: v.x, y: axisY + (v.y - axisY) * roll });
    ffoot = r(ffoot); bfoot = r(bfoot); fhand = r(fhand); bhand = r(bhand);
    head = { x: neck.x - .9 * f * s, y: axisY + (roll >= 0 ? -.9 : .9) * s };
  }
  const bend = (a: Vec, b: Vec, len: number, dir: number): Vec => {
    const dx = b.x - a.x, dy = b.y - a.y, d = Math.max(.001, Math.hypot(dx, dy));
    const arch = Math.sqrt(Math.max(0, len * len / 4 - d * d / 4)) * dir * f;
    return { x: (a.x + b.x) / 2 - dy / d * arch, y: (a.y + b.y) / 2 + dx / d * arch };
  };
  const rig = {
    hip, neck, head, ffoot, bfoot, fhand, bhand,
    fknee: bend(hip, ffoot, 6.9 * s, -1), bknee: bend(hip, bfoot, 6.7 * s, -1),
    felbow: bend(neck, fhand, 5.1 * s, 1), belbow: bend(neck, bhand, 4.9 * s, -1), trail: null,
  };
  if (o.footLead !== -1) return rig;
  const depth = .44 * s * f;
  const shift = (v: Vec, dx: number, dy = 0) => ({ x: v.x + dx, y: Math.min(0, v.y + dy) });
  return { ...rig,
    ffoot: shift(rig.bfoot, -depth, -.17 * s), bfoot: shift(rig.ffoot, depth, .13 * s),
    fknee: shift(rig.bknee, -depth * .72), bknee: shift(rig.fknee, depth * .72),
  };
}